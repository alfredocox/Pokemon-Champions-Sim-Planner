#!/usr/bin/env node
import fs from 'node:fs/promises';
import path from 'node:path';
import vm from 'node:vm';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { assembleFeed, parseSource, safeUrl } from './news-feed-core.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT_PATH = path.join(ROOT, 'generated', 'news_feed.js');

export function readGeneratedFeed(code) {
  const root = {};
  vm.runInNewContext(String(code || ''), { window: root, self: root, globalThis: root }, { timeout: 1000 });
  return root.CHAMPIONS_NEWS_FEED || {};
}

export function chooseFeedUpdate(existing, candidate) {
  if (candidate.source_count > 0 && candidate.errors.length === candidate.source_count) {
    return { shouldWrite: true, payload: { ...candidate, generated_at: existing.generated_at || null, last_attempt_at: candidate.generated_at }, failed: true,
      warning: 'All news sources unavailable; only policy-compatible last-known-good items retained as stale.' };
  }
  return { shouldWrite: true, payload: candidate, failed: false, warning: '' };
}

export async function fetchSource(source, fetcher = fetch) {
  let url = source.url;
  const signal = AbortSignal.timeout(15000);
  for (let redirect = 0; redirect < 4; redirect++) {
    if (!safeUrl(url, undefined, source.fetch_hosts)) throw new Error('Source URL is outside the approved host list');
    const response = await fetcher(url, { signal, redirect: 'manual', headers: { 'user-agent': 'champions-news-inventory/2.0' } });
    if ([301, 302, 303, 307, 308].includes(response.status)) {
      const location = response.headers.get('location');
      await response.body?.cancel();
      if (!location) throw new Error('Redirect missing Location');
      url = new URL(location, url).href;
      continue;
    }
    if (!response.ok) { await response.body?.cancel(); throw new Error('HTTP ' + response.status); }
    let size = 0;
    const chunks = [];
    for await (const chunk of response.body) {
      size += chunk.length;
      if (size > 4 * 1024 * 1024) throw new Error('Source exceeds 4 MiB response limit');
      chunks.push(chunk);
    }
    return Buffer.concat(chunks).toString('utf8');
  }
  throw new Error('Too many source redirects');
}

export async function refreshFeed(config, existing, { fetcher = fetch, now = new Date().toISOString() } = {}) {
  if (!config.sources.some(source => source.enabled)) throw new Error('No enabled news sources');
  const results = [];
  for (const source of config.sources.filter(s => s.enabled)) {
    try {
      const body = await fetchSource(source, fetcher);
      results.push({ source_id: source.id, items: parseSource(body, source, now), sha256: crypto.createHash('sha256').update(body).digest('hex') });
    } catch (error) { results.push({ source_id: source.id, error: error.message }); }
  }
  const candidate = assembleFeed(config, existing, results, now);
  return chooseFeedUpdate(existing, candidate);
}

async function main() {
  const config = JSON.parse(await fs.readFile(path.join(ROOT, 'tools', 'news_sources.json'), 'utf8'));
  let existing = {};
  try { existing = readGeneratedFeed(await fs.readFile(OUT_PATH, 'utf8')); } catch { /* First run has no fallback. */ }
  const update = await refreshFeed(config, existing);
  const candidate = update.payload;
  const reportPath = path.join(ROOT, 'reports', 'news-sync-health.json');
  await fs.mkdir(path.dirname(reportPath), { recursive: true });
  await fs.writeFile(reportPath, JSON.stringify({ checked_at: candidate.last_attempt_at || candidate.generated_at, sources: candidate.source_health }, null, 2) + '\n');
  const encoded = JSON.stringify(candidate).replace(/</g, '\\u003c').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
  await fs.writeFile(OUT_PATH, '// Generated by tools/sync-news-feed.mjs. Do not edit by hand.\n(function(root) {\n  root.CHAMPIONS_NEWS_FEED = ' + encoded + ';\n})(typeof self !== \'undefined\' ? self : (typeof window !== \'undefined\' ? window : globalThis));\n');
  console.log('News: ' + candidate.item_count + ' dated items, ' + candidate.errors.length + '/' + candidate.source_count + ' sources unavailable.');
  for (const row of candidate.source_health) console.log(row.source_id + ': ' + row.status + ' (' + row.eligible_count + ')' + (row.error ? ' ' + row.error : ''));
  if (update.failed) { console.error(update.warning); process.exitCode = 1; }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  main().catch(error => { console.error(error); process.exitCode = 1; });
}
