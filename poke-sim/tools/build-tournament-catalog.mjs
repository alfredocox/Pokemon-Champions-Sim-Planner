import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export function validateCatalog(catalog) {
  if (catalog.format !== 'doubles') throw new Error('Tournament catalog must explicitly use doubles');
  if (catalog.schema_version !== 1 || catalog.status !== 'review_only_not_runtime_promoted' || !Array.isArray(catalog.teams) || catalog.teams.length !== 13) {
    throw new Error('Invalid review-only Worlds catalog');
  }
  if (catalog.event_id !== 'WCS02wAQpCIaqFmXxER4' || catalog.division !== 'Masters' || !Number.isFinite(Date.parse(catalog.checked_at))) throw new Error('Invalid event scope');
  const ids = new Set();
  for (const team of catalog.teams) {
    if (team.format !== undefined && team.format !== catalog.format) throw new Error('Team format conflicts with doubles catalog');
    if (!team.id || !team.player || ids.has(team.id)) throw new Error('Duplicate/missing team identity');
    ids.add(team.id);
    const url = new URL(team.source.url);
    if (url.origin !== 'https://rk9.gg' || !url.pathname.startsWith(`/teamlist/public/${catalog.event_id}/`) || !/^[a-f0-9]{64}$/.test(team.source.sha256)) throw new Error('Invalid sheet provenance');
    if (!Number.isFinite(Date.parse(team.source.retrieved_at)) || team.final_placement !== null || team.stage !== 'top_cut') throw new Error('Unreviewed provenance or placement');
    if (team.simulation_status !== 'blocked_missing_stats_and_ruleset_review' || team.members.length !== 6) throw new Error('Unreviewed simulation promotion');
    team.members.forEach((member, index) => {
      if (member.member_id !== `${team.id}:slot-${index + 1}` || member.registered_slot !== index + 1 || ids.has(member.member_id)) throw new Error('Invalid member identity');
      ids.add(member.member_id);
      if (member.stat_points !== null || member.battle_stats !== null) throw new Error('Unverified stats must remain unknown');
      if (!member.species || !member.item || !member.ability || !member.stat_alignment || member.moves.length !== 4 || new Set(member.moves).size !== 4) throw new Error('Invalid open sheet');
    });
  }
  return catalog;
}

export function generateCatalog(catalog) {
  validateCatalog(catalog);
  return '// Generated by tools/build-tournament-catalog.mjs; review-only, never TEAMS.\nvar CS_TOURNAMENT_CATALOG = ' + JSON.stringify(catalog, null, 2).replace(/</g, '\\u003c') + ';\n';
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const catalog = JSON.parse(readFileSync(new URL('../source/worlds-2026-masters-top-cut.json', import.meta.url), 'utf8'));
  writeFileSync(new URL('../generated/tournament_catalog.js', import.meta.url), generateCatalog(catalog));
  console.log('Built 13 review-only tournament teams. Runtime catalog unchanged.');
}
